DROP TABLE IF EXISTS t_command_audit_event;
DROP TABLE IF EXISTS t_command_approval;

CREATE TABLE t_command_approval (
    approval_id VARCHAR(64) PRIMARY KEY,
    idempotency_key VARCHAR(128) NOT NULL,
    student_id INT NOT NULL,
    project_id INT NOT NULL,
    task_id BIGINT NOT NULL,
    conversation_id VARCHAR(64),
    session_id VARCHAR(128),
    source VARCHAR(64) NOT NULL,
    invocation_id VARCHAR(128) NOT NULL,
    tool_call_id VARCHAR(128),
    command_digest VARCHAR(64) NOT NULL,
    canonical_command VARCHAR(10000) NOT NULL,
    display_command VARCHAR(10000) NOT NULL,
    working_directory VARCHAR(2048) NOT NULL,
    shell VARCHAR(64) NOT NULL,
    command_options VARCHAR(10000) NOT NULL,
    classification VARCHAR(64) NOT NULL,
    policy_version VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    decision_idempotency_key VARCHAR(128),
    decision_time TIMESTAMP,
    decided_by_student_id INT,
    expires_time TIMESTAMP NOT NULL,
    consumed_time TIMESTAMP,
    create_time TIMESTAMP,
    update_time TIMESTAMP,
    CONSTRAINT uk_command_approval_owner_idempotency UNIQUE (student_id, project_id, idempotency_key)
);

CREATE TABLE t_command_audit_event (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_id VARCHAR(64) NOT NULL,
    student_id INT NOT NULL,
    project_id INT NOT NULL,
    task_id BIGINT NOT NULL,
    conversation_id VARCHAR(64),
    session_id VARCHAR(128),
    event_type VARCHAR(48) NOT NULL,
    source VARCHAR(64) NOT NULL,
    invocation_id VARCHAR(128) NOT NULL,
    tool_call_id VARCHAR(128) NOT NULL,
    command_digest VARCHAR(64) NOT NULL,
    classification VARCHAR(64) NOT NULL,
    policy_version VARCHAR(64) NOT NULL,
    decision VARCHAR(32),
    execution_status VARCHAR(32),
    exit_code INT,
    duration_ms BIGINT,
    output_digest VARCHAR(64),
    output_size_bytes BIGINT,
    idempotency_key VARCHAR(192) NOT NULL,
    create_time TIMESTAMP,
    CONSTRAINT uk_command_audit_approval_idempotency UNIQUE (approval_id, idempotency_key)
);
